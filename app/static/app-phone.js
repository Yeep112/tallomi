'use strict';
/* Tallomi: Settings -> 手機連線 (use the book from a phone). Only shown on the computer itself; see app/remote.py. */

function phoneQr(text) {
  const box = h('div', { class: 'qr', role: 'img', 'aria-label': '配對用的 QR code' });
  try {
    const q = qrcode(0, 'M'); q.addData(text); q.make();
    box.innerHTML = q.createSvgTag({ cellSize: 4, margin: 2, scalable: true });      // generated by the library from numbers only
  } catch { box.textContent = '網址太長，無法產生 QR code，請手動輸入配對碼。'; }
  return box;
}

async function settingsPhone(view) {
  let info = await api('GET', '/api/remote');
  const box = h('div', { class: 'rows' });
  let timer = null, codeInfo = null;

  const paint = () => {
    clearInterval(timer);
    const kids = [];
    kids.push(h('p', { class: 'hint', style: 'margin:0' }, '資料一直放在這台電腦。手機透過你私人的 Tailscale 網路連回來，不經過任何別人的伺服器；每支手機要先用配對碼配對一次。' +
      '手機和電腦的記帳會即時互相更新。'));
    kids.push(h('label', { class: 'row-inline' }, h('input', { type: 'checkbox', checked: info.enabled, onchange: async (e) => {
      try { info = await api('PUT', '/api/remote', { enabled: e.target.checked }); codeInfo = null; paint(); toast(info.enabled ? '已開啟手機連線' : '已關閉手機連線，所有手機都連不進來'); }
      catch (er) { fail(er); e.target.checked = !e.target.checked; }
    } }), h('span', null, h('b', null, '允許手機連線'), info.enabled ? '（程式開著、電腦開機時手機才連得上）' : '')));
    if (info.enabled) {
      const urlIn = h('input', { value: info.url || '', placeholder: '例如 https://my-pc.tail1234.ts.net', 'aria-label': '手機要開的網址', autocomplete: 'off', spellcheck: 'false', style: 'min-width:min(300px,100%)' });
      urlIn.addEventListener('change', async () => { try { info = await api('PUT', '/api/remote', { url: urlIn.value }); toast('已儲存網址'); paint(); } catch (er) { fail(er); } });
      kids.push(h('label', { class: 'field' }, h('span', null, '手機要開的網址'), urlIn,
        h('span', { class: 'hint' }, '執行 enable_phone_access.bat 後會顯示這個網址，貼在這裡就能產生 QR code（只存在這台電腦）。')));
      kids.push(h('div', { class: 'row-inline' }, h('button', { class: 'btn primary', type: 'button', onclick: newCode }, codeInfo ? '重新產生配對碼' : '產生配對碼')));
      if (codeInfo) {
        const left = h('span', { class: 'hint' });
        const tick = () => {
          const s = Math.max(0, Math.round((codeInfo.until - Date.now()) / 1000));
          left.textContent = s ? `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')} 內有效，只能用一次` : '已過期，請重新產生';
          if (!s) clearInterval(timer);
        };
        kids.push(h('div', { class: 'pair-box' },
          h('div', null, h('div', { class: 'pair-code', 'aria-live': 'polite' }, `${codeInfo.code.slice(0, 4)} ${codeInfo.code.slice(4)}`), left,
            h('p', { class: 'hint' }, '在手機打開上面的網址，輸入這 8 位數字' + (info.url ? '；或直接用手機相機掃右邊的 QR code。' : '。'))),
          info.url ? phoneQr(`${info.url}/pair#${codeInfo.code}`) : null));
        tick(); timer = setInterval(tick, 1000);
      }
      kids.push(h('div', { class: 'field' }, h('span', { style: 'font-weight:500' }, `已配對的手機（${info.devices.length}）`),
        info.devices.length ? h('table', { class: 'ledger' }, h('tbody', null, info.devices.map((d) => h('tr', null,
          h('td', { class: 'name' }, h('input', { class: 'devname', value: d.name, maxlength: 40, 'aria-label': '手機名稱', onchange: async (e) => {
            try { info = await api('PUT', `/api/remote/devices/${d.id}`, { name: e.target.value }); toast('已改名'); } catch (er) { fail(er); }
          } })),
          h('td', { class: 'hint' }, `最近使用 ${shortTime(d.last_seen)}`),
          h('td', { class: 'act' }, h('button', { class: 'btn sm ghost', type: 'button', onclick: async () => {
            if (!(await confirmBox({ title: `移除「${d.name}」？`, message: h('p', null, '這支手機會立刻被登出，要再用配對碼配對才能使用。'), confirmLabel: '移除', danger: true }))) return;
            try { info = await api('DELETE', `/api/remote/devices/${d.id}`); paint(); toast('已移除'); } catch (er) { fail(er); }
          } }, '移除')))))) : h('span', { class: 'hint' }, '還沒有手機。')));
    }
    kids.push(h('details', null, h('summary', { class: 'hint', style: 'cursor:pointer' }, '第一次設定怎麼做？'),
      h('ol', { class: 'steps' },
        h('li', null, '電腦和手機都安裝 Tailscale（免費、tailscale.com），用同一個帳號登入。'),
        h('li', null, '在電腦上雙擊 enable_phone_access.bat：它會讓 Tailscale 提供一個只有你的裝置連得到的 https 網址，並讓 Tallomi 開機自動在背景執行。把網址貼到上面的欄位。'),
        h('li', null, 'Android：按「產生配對碼」，用 Chrome 掃 QR code（或打開網址、輸入配對碼），配對後按「⋮」→「安裝應用程式」。'),
        h('li', null, 'iPhone：順序相反。先用 Safari 打開網址 →「分享」→「加入主畫面」，再從主畫面開啟 Tallomi，在 App 裡輸入配對碼（iPhone 的主畫面 App 和 Safari 登入狀態是分開的，掃 QR code 配對不會帶進 App）。'),
        h('li', null, '不需要時，關掉上面的開關，或按「移除」，手機就連不進來了。')),
      h('p', { class: 'hint' }, '手機開著這個 App 時，電腦上新增或修改的資料幾秒內就會出現；反過來也一樣。電腦關機或睡眠時手機會顯示「連不上你的電腦」，資料不會遺失（都在電腦）。')));
    box.replaceChildren(...kids);
  };
  async function newCode() {
    try { const r = await api('POST', '/api/remote/code'); codeInfo = { code: r.code, until: Date.now() + r.expires_in * 1000 }; paint(); } catch (e) { fail(e); }
  }
  view.append(h('section', { class: 'section' }, h('div', { class: 'section-head' }, h('h2', null, '手機連線')), box));
  paint();
}
